import { writeFile } from "node:fs/promises";
import { getTweet } from "react-tweet/api";
import { communityPostUrls } from "../src/data/recap.ts";

const tweets = await Promise.all(
  communityPostUrls.map(async (url) => {
    const tweet = await getTweet(new URL(url).pathname.split("/").at(-1) ?? "");
    if (!tweet) {
      throw new Error(`X returned no tweet for ${url}`);
    }
    return tweet;
  })
);

await writeFile(
  new URL("../src/data/community-tweets.ts", import.meta.url),
  `// Generated by \`pnpm --filter web tweets:snapshot\`; do not edit.
import type { Tweet } from "react-tweet/api";

// react-tweet's getTweet types X's payload as Tweet without validating it, and
// X omits fields that type requires; this is that same payload, unchanged.
export const communityTweets = JSON.parse(${JSON.stringify(JSON.stringify(tweets))}) as Tweet[];
`
);
